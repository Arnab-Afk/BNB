/**
 * generate-contracts.js
 *
 * Generates two production-ready Solidity contracts:
 *   1. contracts/PoseidonHasher.sol  — uses circomlibjs Poseidon T3 constants
 *   2. circuits/        (compilation step — see setup-zk.ps1)
 *
 * Usage:
 *   node scripts/generate-contracts.js
 *
 * Requires:
 *   npm install circomlibjs
 */

const { buildPoseidon, poseidonContract } = require("circomlibjs");
const fs = require("fs");
const path = require("path");

async function main() {
    console.log("\n👻 Ghost Privacy Suite — Contract Generator\n");

    // ── 1. Generate PoseidonHasher.sol ─────────────────────────────────────────
    console.log("→  Building Poseidon T3 (2-input) contract from circomlibjs...");

    // circomlibjs generates a complete, gas-optimal Solidity contract
    // with all round constants hardcoded as assembly opcodes.
    const abi = poseidonContract.generateABI(2);       // T3 = 2 inputs
    const bytecode = poseidonContract.createCode(2);        // inline assembly

    // We need a wrapper that implements our IPoseidonHasher interface.
    // The circomlibjs-generated contract has a different ABI:
    //   function poseidon(uint256[2] memory) returns (uint256)
    // Our interface expects:
    //   function poseidon(bytes32 left, bytes32 right) returns (bytes32)

    const wrapperSol = `// SPDX-License-Identifier: MIT
// AUTO-GENERATED by scripts/generate-contracts.js — DO NOT EDIT MANUALLY.
// Source: circomlibjs poseidonContract.createCode(2)
// This uses the EXACT same Poseidon parameters as the ZK circuit (BN254, t=3).
pragma solidity ^0.8.24;

import "./interfaces/IPoseidonHasher.sol";

/**
 * @title PoseidonT3 — circomlibjs inner contract (auto-generated assembly)
 * @dev   Contains the hardcoded round constants and MDS matrix for Poseidon T3.
 *        Deployed by PoseidonHasher's constructor via CREATE.
 */
contract PoseidonT3Inner {
    fallback() external {
        // Auto-generated assembly with all round constants inline.
        // Gas: ~28,000 per call.
        ${generateAssemblyStub()}
    }
}

/**
 * @title  PoseidonHasher
 * @notice Wraps the circomlibjs Poseidon T3 contract to implement IPoseidonHasher.
 * @dev    Uses the identical constants as \`circomlibjs.buildPoseidon()\` so
 *         ZK proofs generated off-chain are compatible with on-chain tree roots.
 */
contract PoseidonHasher is IPoseidonHasher {

    address private immutable _inner;

    constructor() {
        // Deploy the inner assembly contract
        PoseidonT3Inner inner = new PoseidonT3Inner();
        _inner = address(inner);
    }

    /// @inheritdoc IPoseidonHasher
    function poseidon(bytes32 left, bytes32 right) external view override returns (bytes32 hash) {
        uint256[2] memory inputs;
        inputs[0] = uint256(left);
        inputs[1] = uint256(right);

        // Call the inner Poseidon T3 contract
        (bool ok, bytes memory result) = _inner.staticcall(abi.encode(inputs));
        require(ok, "Poseidon call failed");
        hash = bytes32(abi.decode(result, (uint256)));
    }
}
`;

    // Write the wrapper
    const hasherPath = path.join(__dirname, "..", "contracts", "PoseidonHasher.sol");
    fs.writeFileSync(hasherPath, wrapperSol);
    console.log("✓  Written: contracts/PoseidonHasher.sol");

    // ── 2. Generate PoseidonHasherDeployer for the inner bytecode ──────────────
    // The actual constants come from the bytecode. For Hardhat, we deploy via
    // a factory that embeds the circomlibjs bytecode as a hex literal.

    const deployerSol = `// SPDX-License-Identifier: MIT
// AUTO-GENERATED — DO NOT EDIT MANUALLY. Run: node scripts/generate-contracts.js
pragma solidity ^0.8.24;

import "./interfaces/IPoseidonHasher.sol";

/**
 * @title  PoseidonHasher
 * @notice Production Poseidon T3 hasher with circomlibjs constants.
 *         The inner contract bytecode contains all round constants for BN254 Poseidon.
 * @dev    Uses CREATE to deploy inner contract, then delegates all calls to it.
 *         This matches the exact Poseidon implementation used by snarkjs/circomlibjs.
 */
contract PoseidonHasher is IPoseidonHasher {

    address private immutable _poseidonAddr;

    constructor() {
        // Bytecode of the circomlibjs Poseidon T3 (2-input) contract.
        // Generated by: poseidonContract.createCode(2)
        bytes memory bytecode = hex"${bytecode.slice(2)}";
        address poseidon;
        assembly {
            poseidon := create(0, add(bytecode, 0x20), mload(bytecode))
        }
        require(poseidon != address(0), "PoseidonHasher: deploy failed");
        _poseidonAddr = poseidon;
    }

    /// @inheritdoc IPoseidonHasher
    /// @dev Calls the inner circomlibjs Poseidon contract ABI-encoding [left, right].
    function poseidon(bytes32 left, bytes32 right) external view override returns (bytes32 hash) {
        uint256[2] memory inputs = [uint256(left), uint256(right)];
        (bool ok, bytes memory result) = _poseidonAddr.staticcall(abi.encode(inputs));
        require(ok, "PoseidonHasher: call failed");
        hash = bytes32(abi.decode(result, (uint256)));
    }
}
`;

    fs.writeFileSync(hasherPath, deployerSol);
    console.log("✓  PoseidonHasher.sol written with real circomlibjs bytecode embedded.");

    console.log("\n  ✅ Done! Now compile and deploy:");
    console.log("     npm run compile");
    console.log("     npm run deploy:testnet\n");
}

function generateAssemblyStub() {
    return `// placeholder — real code is in the bytecode hex below`;
}

main().catch(e => {
    console.error("❌ Failed:", e.message);
    console.error("\n  Make sure you ran: npm install circomlibjs");
    process.exit(1);
});
